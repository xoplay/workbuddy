export function getFallbackGradient(prefix: string, level: number): string {
  const h1 = (level * 37 + prefix.charCodeAt(0) * 11) % 360;
  const h2 = (h1 + 120 + level * 13) % 360;
  
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="1080" height="1920">
    <defs>
      <linearGradient id="g" x1="0%" y1="0%" x2="100%" y2="100%">
        <stop offset="0%" stop-color="hsl(${h1}, 70%, 50%)" />
        <stop offset="100%" stop-color="hsl(${h2}, 70%, 30%)" />
      </linearGradient>
    </defs>
    <rect width="1080" height="1920" fill="url(#g)" />
    <text x="50%" y="50%" font-family="sans-serif" font-size="80" fill="white" font-weight="bold" text-anchor="middle" dominant-baseline="middle">
      ${prefix.toUpperCase()} - LEVEL ${level}
    </text>
  </svg>`;
  
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`;
}

// Return local image URL only (no remote fallback)
// 路径统一由 manifest 模板生成（挑战 prefix='g' → /img/g/g{n}.webp）
import { buildPathSync } from './manifest';
export function getStageImage(prefix: string, level: number): { local: string; fallback: string } {
  const safeLevel = isNaN(level) || typeof level !== 'number' ? 1 : level;

  // 仅使用本地图片（按序列顺位，不使用任何远程 fallback）
  const localUrl = buildPathSync(prefix, safeLevel);

  return {
    local: localUrl,
    fallback: localUrl,
  };
}

